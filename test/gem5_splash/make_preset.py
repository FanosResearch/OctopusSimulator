#!/usr/bin/env python3
"""Writes configuration/SystemConfigurations/MultiCoreSystem_gem5_mesh_ruby.csv, the Octopus side of
the gem5 Ruby/Garnet comparison (docs/gem5_SPLASH_Garnet_vs_Octopus.md). Rerun after editing a
value here; the CSV is the artifact gem5 reads.

Tile t (router t of the 4x4 mesh): instruction L1 t, data L1 16+t, LLC bank 64+t and the bank's
memory port 80+t. Memory controllers 100 and 101 sit on routers MEM_ROUTERS, as the two Ruby
directory controllers do in se_arm_ruby.py.
"""
import os

K = 4
N = K * K
L1I = list(range(N))
L1D = [N + t for t in range(N)]
BANK = [64 + t for t in range(N)]
MPORT = [80 + t for t in range(N)]
MEM = [100, 101]
MEM_ROUTERS = [4, 11]          # (x,y) = (0,1) and (3,2): the middle of the west and east edges

L1_SIZE, L1_WAYS = 32 * 1024, 8
BANK_SIZE, BANK_WAYS = 512 * 1024, 8
# Each bank indexes its sets with the bank-select digit removed (CacheDataHandler, set by
# MultiCoreSystem_Mesh from the cores' home map), so a 512 KiB 8-way bank uses all of its 1024 sets:
# set = address bits 10-19, the same set mapping as Ruby's L2 with start_index_bit 10.

rows = []
def kv(key, *vals, comment=""):
    cells = [key] + [str(v) for v in vals]
    if comment:
        cells.append("#" + comment)
    rows.append(",".join(cells))

kv("workload_path(s)", "log/", comment="Overridden by the gem5 bridge with its output directory")
rows.append("#gem5 Ruby/Garnet comparison preset (docs/gem5_SPLASH_Garnet_vs_Octopus.md), generated by "
            "test/gem5_splash/make_preset.py: 16 tiles on a 4x4 grid2d Network with XY routing and Garnet-mapped "
            "timing (1+1 cycles per hop), directory MESI, 32 KiB 8-way L1I/L1D, 16 LLC banks of 512 KiB 8-way "
            "interleaved by line, two MCsim DDR4-2400 controllers on the network (routers 4 and 11)")
kv("num_cores(i)", 2 * N, comment="gem5 L1 bridges: instruction caches 0-15, data caches 16-31")
kv("cpu_type(s)", "ExternalCPU")
kv("cache_controller_type(s)", "CacheControllerDirectory")
kv("requires_ordering(s)", "pair_per_class", comment="the directory protocol needs same-class same-pair order; XY gives it only with one VC per class")
kv("llc_banks(i)", N)
kv("memory_on_network(i)", 1, comment="memory controllers and the banks' memory ports are network endpoints (spec s25)")
rows.append("")
kv("interconnect_type(s)", "Network")
kv("interconnect.topology(s)", "grid2d")
kv("interconnect.dims(vi)", K, K)
kv("interconnect.component_ids(vi)", *(L1I + L1D + BANK + MPORT + MEM))
for t in range(N):
    for cid in (L1I[t], L1D[t], BANK[t], MPORT[t]):
        kv(f"interconnect.node_map[{cid}](i)", t)
for m, r in zip(MEM, MEM_ROUTERS):
    kv(f"interconnect.node_map[{m}](i)", r, comment="memory controller")
kv("interconnect.routing(s)", "XY")
kv("interconnect.num_classes(i)", 3, comment="request / forward / response")
kv("interconnect.vcs_per_class(i)", 1, comment="Garnet uses 4 VCs per vnet; pair_per_class with XY needs 1")
kv("interconnect.vc_depth(i)", 4, comment="Garnet buffers_per_data_vc (and buffers_per_ctrl_vc in se_arm_ruby.py)")
kv("interconnect.flit_bytes(i)", 16, comment="Garnet ni_flit_size")
kv("interconnect.header_bytes(i)", 8, comment="64 B line + 8 B = 5 flits, as Garnet's 72 B Data message")
kv("interconnect.router_latency(i)", 0, comment="Garnet router_latency 1 (single-cycle router, docs/NoC_Garnet_Validation.md s2)")
kv("interconnect.link_latency(i)", 2, comment="Garnet link_latency 1 plus the switch-to-link cycle: 2 cycles per hop")
kv("interconnect.credit_latency(i)", 2)
kv("interconnect.sa_allocator(s)", "input_first", comment="Garnet SwitchAllocator: input ports first")
kv("interconnect.arbiter_type(s)", "RRArbiter")
kv("interconnect.m_clk_period(i)", 100, comment="network at the core clock")
kv("interconnect.inject_queue_depth(i)", 32)
kv("interconnect.eject_queue_depth(i)", 32)
kv("interconnect.buffers_max_size(i)", 32, comment="legacy key (not read by Network)")
rows.append("")
kv("cpu_interconnect[*].buffers_max_size(i)", 64, comment="= processing_queue_size")
kv("cpu_interconnect[*].m_clk_period(i)", 50)
kv("cpu[*].m_clk_period(i)", 100, comment="one gem5 core cycle = 100 Octopus ns")
rows.append("")
kv("cache_controller[*].m_shared_memory_id(i)", BANK[0])
kv("cache_controller[*].home_ids(vi)", *BANK)
kv("cache_controller[*].home_interleave_shift(i)", 0, comment="consecutive lines go to consecutive banks (Ruby l2_select bits 6-9)")
kv("cache_controller[*].protocol_type(s)", "DIRECTORY_MESI")
kv("cache_controller[*].fsm_filename(s)", "MESI_directory_v2")
kv("cache_controller[*].m_clk_period(i)", 100)
kv("cache_controller[*].m_data_handler.cache_size(i)", L1_SIZE, comment="32 KiB 8-way L1I and L1D")
kv("cache_controller[*].m_data_handler.m_block_size(i)", 64)
kv("cache_controller[*].m_data_handler.m_ways_count(i)", L1_WAYS)
kv("cache_controller[*].m_data_handler.m_data_access_latency(i)", 0)
kv("cache_controller[*].m_data_handler.replacement_policy_name(s)", "LRU")
kv("cache_controller[*].num_mshr(i)", 16)
kv("cache_controller[*].m_data_handler.pwb_size(i)", 8)
kv("cache_controller[*].processing_queue_size(i)", 64)
kv("cache_controller[*].line_interlock(i)", 1)
for i, cid in enumerate(L1I + L1D):
    kv(f"cache_controller[{i}].m_id(i)", cid)
rows.append("")
for k, cid in enumerate(BANK):
    kv(f"llc_controller[{k}].m_id(i)", cid)
    kv(f"llc_controller[{k}].mem_port_id(i)", MPORT[k])
kv("llc_controller[*].mem_ids(vi)", *MEM)
kv("llc_controller[*].mem_interleave_shift(i)", 0, comment="line-interleaved channels, as gem5's DualChannelDDR4_2400 (64 B)")
kv("llc_controller[*].m_shared_memory_id(i)", MEM[0])
kv("llc_controller[*].protocol_type(s)", "DIRECTORY_LLC_MESI")
kv("llc_controller[*].fsm_filename(s)", "MESI_LLC_directory_v2")
kv("llc_controller[*].m_clk_period(i)", 100)
kv("llc_controller[*].m_data_handler.cache_size(i)", BANK_SIZE,
   comment="512 KiB 8-way per bank (8 MiB in total)")
kv("llc_controller[*].m_data_handler.m_block_size(i)", 64)
kv("llc_controller[*].m_data_handler.m_ways_count(i)", BANK_WAYS)
kv("llc_controller[*].m_data_handler.m_data_access_latency(i)", 10)
kv("llc_controller[*].m_data_handler.m_data_array_pipelined(i)", 1)
kv("llc_controller[*].m_data_handler.m_data_array_ports(i)", 1)
kv("llc_controller[*].m_data_handler.replacement_policy_name(s)", "LRU")
kv("llc_controller[*].num_mshr(i)", 16)
kv("llc_controller[*].m_data_handler.pwb_size(i)", 8)
kv("llc_controller[*].processing_queue_size(i)", 32)
kv("llc_controller[*].line_interlock(i)", 1)
kv("llc_controller[*].arbiter_type(s)", "FCFSArbiter")
kv("llc_controller[*].arbiter_candidates_ids(vi)", *(L1I + L1D))
rows.append("")
kv("main_memory_type(s)", "MCsim", comment="DDR4-2400U 8Gb x8, 1 rank per controller (MCsimInterface)")
kv("mcsim_core_clock_mhz(i)", 3000, comment="the gem5 CPU clock")
kv("m_main_memory.m_llc_id(i)", BANK[0])
kv("m_main_memory.m_id(i)", MEM[0])
rows.append("")
for c in ("cache_controller[*]", "llc_controller[*]"):
    kv(f"{c}.dprint.enable(i)", 0)
    kv(f"{c}.dprint.target(s)", "BMs/testDPrint/dprint.csv")
    kv(f"{c}.dprint.addr_filter(s)", "")
    kv(f"{c}.dprint.cond_addr(vs)", "")

root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")
out = os.path.join(root, "configuration", "SystemConfigurations", "MultiCoreSystem_gem5_mesh_ruby.csv")
with open(out, "w") as f:
    f.write("\n".join(rows) + "\n")
print(out)
